const assert=require('node:assert/strict');
global.KEYS=require('../wallpaper/layout.js').KEYS;
global.keySurfaces=require('../wallpaper/surfaces.js');
const game=require('../wallpaper/games.js');
const advance=ms=>{while(ms>0){const d=Math.min(ms,100);game.step(d);ms-=d;}};
game.reset(4);game.step(0);
assert.equal(game.state.targets.length,1);
let target=game.state.targets[0];
assert.equal(game.press('Unknown'),0);
assert.equal(game.press(target.code),1);
assert.equal(game.press(target.code),0,'target cannot score twice');
assert.equal(game.state.hits,1);
advance(10000);assert(game.state.targets.length<=3);assert(game.state.misses>0,'missed targets expire');
assert.equal(new Set(game.state.targets.map(t=>t.code)).size,game.state.targets.length);
game.reset(5);game.step(0);target=game.state.targets[0];
assert.equal(game.press(target.code),0,'too early');advance(1600);
assert.equal(game.press(target.code),2,'perfect timing');assert.equal(game.state.hits,1);
game.reset(5);game.step(0);target=game.state.targets[0];advance(1850);
assert.equal(game.press(target.code),0,'late catch rejected');assert(game.state.misses>0);
advance(10000);assert(game.state.targets.length<=4);
game.reset(6);for(let i=0;i<50;i++)game.press('Space');
assert.deepEqual(game.state.plants,[['Space',8]],'growth capped per key');
for(const k of KEYS)game.press(k.code);assert.equal(game.state.plants.length,84);
const snapshot=game.state;snapshot.plants[0][1]=999;assert.equal(game.state.plants[0][1],8,'snapshot does not mutate game');
game.reset(7);game.press('KeyA');let crack=game.state.cracks[0];assert.equal(crack.damage,1);
advance(1000);assert.equal(game.state.cracks[0].damage,1,'repair waits after impact');
advance(3000);assert(game.state.cracks[0].damage<1,'cracks slowly repair');
const remaining=game.state.cracks[0].damage;game.press('KeyA');assert.equal(game.state.cracks[0].damage,remaining+1,'repeated impact adds to remaining crack');
assert.equal(game.state.cracks[0].seed,crack.seed,'existing fracture geometry preserved');
for(let i=0;i<30;i++)game.press('KeyA');assert.equal(game.state.cracks[0].damage,8,'damage bounded');
game.press('KeyB');assert.equal(game.state.cracks.length,2,'keys have separate fractures');
advance(14000);assert.equal(game.state.cracks.length,0,'full repair removes fracture');

game.press('KeyA');advance(800);game.release('KeyA');
assert.equal(game.state.cracks[0].lastHit,game.state.time,'repair delay starts at release');
advance(1500);assert.equal(game.state.cracks[0].damage,1,'no repair before release delay');
advance(200);assert(game.state.cracks[0].damage<1,'repair begins after release delay');
game.release('Unknown');
game.press('KeyA');game.reset(0);assert.equal(game.state.hits,0);assert.equal(game.state.targets.length,0);assert.equal(game.state.plants.length,0);assert.equal(game.state.cracks.length,0);
game.step(NaN);game.step(-1);assert.equal(game.state.time,0);
game.step(180);assert.equal(game.state.time,180,'low FPS preserves accelerated game time');
game.step(10000);assert.equal(game.state.time,380,'large resume jumps remain bounded');
console.log('PASS: game hits/caps, growth limits, additive glass damage, stable fracture, slow/full repair, reset, invalid clock');

